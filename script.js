const fishImage = document.getElementById("fish-image");

const speciesSelect =
    document.getElementById("species-select");

const submitButton =
    document.getElementById("submit-button");

const nextButton =
    document.getElementById("next-button");

const result =
    document.getElementById("result");

const scoreDisplay =
    document.getElementById("score");

const questionNumberDisplay =
    document.getElementById("question-number");


// ==========================================
// GAME VARIABLES
// ==========================================

let currentFish = null;

let score = 0;

let questionNumber = 1;

let answered = false;


// ==========================================
// CREATE THE SPECIES DROPDOWN
// ==========================================

// Get every unique species from the fish database.

const species = [...new Set(
    fish.map(f => f.species)
)];

// Sort species alphabetically
species.sort((a, b) => a.localeCompare(b));

species.forEach(speciesName => {

    const option = document.createElement("option");

    option.value = speciesName;

    option.textContent = speciesName;

    speciesSelect.appendChild(option);

});


// ==========================================
// RANDOM FISH
// ==========================================

function loadRandomFish() {

    answered = false;

    result.textContent = "";
    result.className = "result";

    speciesSelect.value = "";

    submitButton.style.display = "block";
    nextButton.style.display = "none";

    const randomIndex =
        Math.floor(Math.random() * fish.length);

    currentFish = fish[randomIndex];

    // Show a temporary loading message
    fishImage.style.display = "none";

    // Create a new image to preload the photograph
    const newImage = new Image();

    newImage.onload = function() {

        fishImage.src = currentFish.image;

        fishImage.alt = "Anemonefish to identify";

        fishImage.style.display = "block";

    };

    newImage.onerror = function() {

        console.error(
            "Could not load image:",
            currentFish.image
        );

        result.textContent =
            "Error loading image: " +
            currentFish.image;

        result.className = "result incorrect";
    };

    newImage.src = currentFish.image;

    questionNumberDisplay.textContent =
        questionNumber;
}


// ==========================================
// CHECK THE ANSWER
// ==========================================

function checkAnswer() {

    // Prevent the player from submitting twice.

    if (answered) {
        return;
    }


    // Make sure they selected something.

    if (speciesSelect.value === "") {

        result.textContent =
            "Please select a species first.";

        result.className = "result incorrect";

        return;
    }


    answered = true;


    const playerAnswer =
        speciesSelect.value;


    const correctAnswer =
        currentFish.species;


    // ======================================
    // CORRECT
    // ======================================

    if (playerAnswer === correctAnswer) {

        score++;

        scoreDisplay.textContent = score;

        result.textContent =
            "✓ Correct! It is " + correctAnswer + ".";

        result.className = "result correct";

    }


    // ======================================
    // INCORRECT
    // ======================================

    else {

        result.textContent =
            "✗ Incorrect. The correct answer is " +
            correctAnswer + ".";

        result.className = "result incorrect";

    }


    // Hide the submit button.

    submitButton.style.display = "none";


    // Show the next button.

    nextButton.style.display = "block";
}


// ==========================================
// NEXT QUESTION
// ==========================================

function nextQuestion() {

    questionNumber++;

    loadRandomFish();
}


// ==========================================
// BUTTON EVENTS
// ==========================================

submitButton.addEventListener(
    "click",
    checkAnswer
);

nextButton.addEventListener(
    "click",
    nextQuestion
);


// ==========================================
// START THE GAME
// ==========================================

loadRandomFish();
